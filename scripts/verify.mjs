/**
 * One-command verification: unit tests + build + deterministic headless replay.
 * Evidence is written to docs/proof/phase-0/ so it can be committed with the tag.
 *
 *   npm run verify
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const proofDir = join(root, 'docs', 'proof', 'phase-0');
const tmpDir = join(root, '.tmp');
mkdirSync(proofDir, { recursive: true });
mkdirSync(tmpDir, { recursive: true });

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: root,
    shell: process.platform === 'win32',
    encoding: 'utf8',
    ...options,
  });
  if (result.status !== 0) {
    process.stdout.write(result.stdout ?? '');
    process.stderr.write(result.stderr ?? '');
    throw new Error(`${command} ${args.join(' ')} failed with code ${result.status}`);
  }
  return `${result.stdout ?? ''}${result.stderr ?? ''}`;
}

const log = [];

// 1. Unit tests
const testOutput = run('npm', ['test']);
writeFileSync(join(proofDir, 'tests.txt'), testOutput, 'utf8');
log.push('## Unit tests\n\n```\n' + testOutput.trim() + '\n```');

// 1b. Type check
const typecheckOutput = run('npm', ['run', 'typecheck']);
log.push('## Type check\n\n`npm run typecheck` passed (tsc --noEmit, 0 errors).');
void typecheckOutput;

// 2. Build the headless bundle exactly as the contract's build_cmd does
run('npm', ['run', 'build:headless']);

// 3. Run the same seed/scenario/inputs twice and compare bytes
const scenario = join('tests', 'fixtures', 'scenario-basic.json');
const inputs = join('tests', 'fixtures', 'walk.json');
const common = [
  'dist/headless.mjs',
  '--seed',
  '7',
  '--night',
  '1',
  '--scenario',
  scenario,
  '--inputs',
  inputs,
  '--ticks',
  '600',
  '--snapshot-every',
  '60',
];

run('node', [...common, '--out', '.tmp/run-a.jsonl']);
run('node', [...common, '--out', '.tmp/run-b.jsonl']);

const hash = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');
const hashA = hash(join(tmpDir, 'run-a.jsonl'));
const hashB = hash(join(tmpDir, 'run-b.jsonl'));
const deterministic = hashA === hashB;

const lastLine = readFileSync(join(tmpDir, 'run-a.jsonl'), 'utf8').trim().split('\n').at(-1);

writeFileSync(
  join(proofDir, 'determinism.txt'),
  [
    `seed=7 scenario=${scenario} inputs=${inputs} ticks=600`,
    `run-a sha256 ${hashA}`,
    `run-b sha256 ${hashB}`,
    `identical: ${deterministic}`,
    `last line: ${lastLine}`,
    '',
  ].join('\n'),
  'utf8',
);

log.push(
  '## Determinism (same seed, scenario, inputs)\n\n' +
    `- run-a: \`${hashA}\`\n- run-b: \`${hashB}\`\n- identical: **${deterministic}**\n- final line: \`${lastLine}\``,
);

if (!deterministic) {
  writeFileSync(join(proofDir, 'summary.md'), log.join('\n\n'), 'utf8');
  throw new Error('headless output is not deterministic');
}

// 4. Error handling: malformed inputs must exit with code 2
const badInputs = join(tmpDir, 'bad-inputs.json');
writeFileSync(badInputs, '{ "frames": [ { "tick": 5 }, { "tick": 5 } ] }', 'utf8');
const bad = spawnSync(
  'node',
  ['dist/headless.mjs', '--seed', '1', '--night', '1', '--inputs', badInputs, '--ticks', '10', '--out', '.tmp/bad.jsonl'],
  { cwd: root, shell: process.platform === 'win32', encoding: 'utf8' },
);
const exitCode = bad.status;
log.push(`## Error handling\n\nMalformed inputs exit code: **${exitCode}** (expected 2)`);
if (exitCode !== 2) {
  writeFileSync(join(proofDir, 'summary.md'), log.join('\n\n'), 'utf8');
  throw new Error(`malformed inputs should exit 2, got ${exitCode}`);
}

writeFileSync(
  join(proofDir, 'summary.md'),
  `# Phase 0 evidence\n\nGenerated by \`npm run verify\` on ${new Date().toISOString()}.\n\n${log.join('\n\n')}\n`,
  'utf8',
);

console.log(`OK — evidence written to ${proofDir}`);
